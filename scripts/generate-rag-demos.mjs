import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const path = p => new URL(p, root);
const course = JSON.parse(readFileSync(path('content/rag.json'), 'utf8'));
const titles = ['对照有无检索证据的回答', '调整分块窗口与重叠', '观察相似度与候选排序', '比较关键词、语义与混合召回', '切换身份，检查权限与有效性', '选择证据，检查引用与拒答', '改变 Top K，核对检索指标', '逐步组装有依据的问答'];
const quote = value => "'" + value.replaceAll("'", "''") + "'";
const safe = value => value.includes('\\') ? 'CONCAT(' + value.split('\\').map(quote).join(',CHAR(92),') + ')' : quote(value);
const updates = [];
let i = 0;
for (const chapter of course.chapters) for (const lesson of chapter.lessons) {
  const config = { kind: 'rag-demo', demoId: lesson.key, title: titles[i++] };
  if (!lesson.body.includes('~~~rag')) lesson.body = lesson.body.replace('## 留下的启发', '~~~rag\n' + JSON.stringify(config, null, 2) + '\n~~~\n\n## 留下的启发');
  updates.push(`UPDATE knowledge_sections SET content_markdown=${safe(lesson.body)},updated_at=CURRENT_TIMESTAMP(3) WHERE knowledge_point_id=(SELECT id FROM knowledge_points WHERE slug='rag') AND node_type='LESSON' AND status='PUBLISHED' AND title=${quote(lesson.title)} AND parent_id IN (SELECT parent.id FROM (SELECT id FROM knowledge_sections WHERE node_type='DIRECTORY' AND title=${quote(chapter.title)}) parent);`);
}
const sql = '-- Generated by scripts/generate-rag-demos.mjs. Preserve course identity, quizzes and reading records.\n\n' + updates.join('\n\n') + '\n';
const migration = path('server/src/main/resources/db/migration/V36__rag_interaction_demonstrations.sql');
if (process.argv.includes('--check')) {
  if (readFileSync(migration, 'utf8') !== sql) throw Error('RAG migration differs');
  console.log('RAG migration and eight lesson configurations agree.');
} else {
  if (existsSync(migration)) throw Error('V36 exists; add a new migration for later revisions');
  writeFileSync(path('content/rag.json'), JSON.stringify(course, null, 2) + '\n');
  writeFileSync(migration, sql);
}
