import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
import { Script } from 'node:vm';
import { agentReferenceDemos } from '../src/agent-reference-demos.ts';

let scripts = 0;
for (const demo of agentReferenceDemos) {
  const path = new URL('../public' + demo.path, import.meta.url);
  const html = readFileSync(path, 'utf8');
  assert.match(html, /<meta\s+name="upstream-source"\s+content="https:\/\/xueai\.miyang\.cn\/slides\//, demo.demoId);
  assert.match(html, /\.\.\/shared\/embed\.js/, demo.demoId);
  assert.match(html, /\.\.\/shared\/lesson\.css/, demo.demoId);
  assert.doesNotMatch(html, /xa_auth|paywall\.js|nav-inject\.js|theme-bridge\.js|watermark\.js|i18n\.js|\bfetch\s*\(|XMLHttpRequest|WebSocket\s*\(/, demo.demoId);
  for (const resource of html.matchAll(/<(script|link)\b[^>]*\b(?:src|href)="([^"]+)"/g)) {
    assert.ok(resource[2].startsWith('../shared/'), demo.demoId + ': unexpected resource ' + resource[2]);
    assert.ok(existsSync(new URL(resource[2], path)), demo.demoId + ': missing ' + resource[2]);
  }
  for (const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/\bsrc=/.test(match[1])) continue;
    new Script(match[2], { filename: demo.demoId + ':inline-' + (++scripts) });
  }
  // References may be static or generated by the same script's HTML templates.
  for (const reference of html.matchAll(/getElementById\(['"]([\w-]+)['"]\)/g)) {
    const id = reference[1];
    assert.ok(new RegExp('id=["\\\']' + id + '["\\\']').test(html), demo.demoId + ': missing referenced node ' + id);
  }
}
for (const name of ['embed.js', 'lesson.js']) new Script(readFileSync(new URL('../public/demos/agent-reference/shared/' + name, import.meta.url), 'utf8'), { filename: name });
assert.match(readFileSync(new URL('../public/demos/agent-reference/LICENSE', import.meta.url), 'utf8'), /GNU AFFERO GENERAL PUBLIC LICENSE/);
console.log(`Verified ${agentReferenceDemos.length} local demonstrations, ${scripts} inline scripts, local dependencies, DOM references and AGPL license.`);
