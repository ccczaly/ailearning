## 把演示连接到真正的系统

演示中，助手先提出行动，再读到结果，最后继续推进或调整计划。真正接入时，模型负责提出工具调用请求，搜索、读取、计算和保存则由程序执行；工具的返回结果再成为下一轮输入。

**四种能力是一种观察系统的方式，不是每个 Agent 都必须配齐的清单。** 简单任务可以不生成显式计划，也可以只使用当前对话，不设置独立的长期记忆。要不要增加这些机制，取决于任务需要。

回到课程费用对比：即使搜索、阅读和保存工具都接齐，乙课程没写价格时，仍然需要判断是补查、询问用户，还是先交付已知信息。如果选择补查，过程就是：发现价格缺失 → 改查官方报名页 → 拿到价格 → 继续比较。

现在再看 Agent，就好理解一些了：**它是一个让模型围绕目标选择行动、借助工具执行，再根据结果调整下一步的系统。** 固定程序也能使用工具；下一节会继续区分聊天机器人、工作流和 Agent，看看行动选择究竟由谁决定。

