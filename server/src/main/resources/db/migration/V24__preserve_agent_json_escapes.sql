## 关键不在于多了几个按钮

刚才，不接工具时，助手只能给建议。接上搜索和阅读后，它能查资料了；接上保存后，才有办法把报告存下来。

不过，**工具接齐了，也不代表任务一定能完成。** 遇到乙课程没写价格的情况，还需要作出判断：换个地方继续查？问用户？还是先交付已知信息？

如果选择补查，过程就是：发现价格缺失 → 改查官方报名页 → 拿到价格 → 继续比较。下一步会受到刚才结果的影响，而不只是照着清单往下做。

现在再看 Agent，就好理解一些了：**它是一个让模型围绕目标选择行动、借助工具执行，再根据结果调整下一步的系统。** 模型提出行动请求，真正搜索、读取和保存的是程序。

固定程序同样可以使用工具。比如“搜两次、生成一份摘要、保存”，每一步都提前写好，也能自动运行。所以，接了工具不等于就是 Agent；我们还要看，哪些行动是由模型根据实际情况选择的。下一节就来分清这件事。

