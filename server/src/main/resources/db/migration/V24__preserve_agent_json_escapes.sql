## 同一个任务，两种做法

假设你对助手说：

> 帮我查一下甲、乙两门课的费用，比较一下，再保存一份报告。

如果它只有对话能力，没有查资料和保存文件的工具，它可以告诉你比较方法，也可以根据你贴来的资料写内容。但它不能因此就替你打开网页、查到价格，再把文件存好。

给它接上合适的工具后，事情就不一样了：它可以提出“搜索课程资料”的请求，由程序真正去搜索；读到内容后，再决定是继续查，还是开始整理报告。

注意，我们没有换一个更复杂的任务。变化的是：**这个助手能做哪些事，以及它拿到结果后会怎么继续。**

